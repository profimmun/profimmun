/**
 * Создаёт стартовый курс с входной анкетой. Идемпотентен (upsert по slug).
 * Секретов не содержит — можно держать в репозитории и запускать на любой базе:
 *   npm run seed:content
 */
import { PrismaClient } from "@prisma/client";
const db = new PrismaClient();

const slug = "vhodnaya-anketa";

const questions = [
  // Общие сведения
  "Ваша должность",
  "Название образовательной организации (полное наименование)",
  "Контактные данные: телефон и электронная почта",
  // Контекст ЦА
  "Какие преимущества есть у вас или вашего учреждения для профилактики деструктивного поведения среди обучающихся?",
  "Представители каких этнических групп обучаются в вашей организации?",
  "Какими документами регламентирована профилактическая работа в вашей организации (стратегические, тактические, операционные)?",
  // Мотивация
  "Почему вы участвуете в этом цикле семинаров?",
  "Какую одну главную проблему вы хотите решить по итогам проекта?",
  "Что для вас главный признак успешной профилактической работы?",
  // Профессиональные вызовы
  "На каком этапе профилактической работы у вас возникает больше всего сложностей?",
  "Какие ситуации в практике вызывают у вас наибольшую тревогу или неуверенность?",
  "Какие темы семинаров для вас сейчас самые важные и почему?",
  // Глубокое осмысление
  "Какие 1–2 вопроса вы задали бы органам контроля и надзора, будь такая возможность?",
  "Какой вопрос представителю определённой этнической группы вы не решаетесь задать и почему?",
  "Какой некоммерческой организации или инициативе вы доверили бы работу с вашими обучающимися и почему?",
  "Чувствуете ли вы эмоциональное выгорание от постоянного обсуждения деструктивного поведения обучающихся?",
].map((text, order) => ({ text, type: "OPEN", points: 1, order }));

const courseData = {
  slug: "profilaktika-destruktivnogo-povedeniya",
  title: "Профилактика деструктивного поведения обучающихся",
  description:
    "Стартовый курс цикла семинаров для педагогов и специалистов образовательных организаций. " +
    "Начните с короткой входной анкеты — по ней организаторы настроят программу под ваши задачи.",
  published: true,
  restricted: false,
};

const lessonContent =
  "Перед началом обучения заполните короткую анкету — это займёт около 5 минут. " +
  "Ответы помогут организаторам адаптировать семинары под ваш опыт, аудиторию и задачи. " +
  "Все вопросы обязательны для заполнения.";

const admin =
  (await db.user.findFirst({ where: { role: "ADMIN" } })) ??
  (await db.user.findFirst());
if (!admin) throw new Error("Нет ни одного пользователя — сначала создайте админа.");

// Ищем курс по slug урока (у урока slug уникален в паре с модулем).
const existingLesson = await db.lesson.findFirst({
  where: { slug },
  include: { module: true },
});

if (existingLesson) {
  await db.course.delete({ where: { id: existingLesson.module.courseId } });
}
// На случай, если курс с таким slug остался от прежнего запуска.
await db.course.deleteMany({ where: { slug: courseData.slug } });

const course = await db.course.create({
  data: {
    ...courseData,
    authorId: admin.id,
    modules: {
      create: [
        {
          title: "Вводный блок",
          order: 0,
          lessons: {
            create: [
              {
                title: "Входная анкета участника",
                slug,
                content: lessonContent,
                videoType: "NONE",
                order: 0,
                published: true,
                tests: {
                  create: [
                    {
                      title: "Входная анкета",
                      description:
                        "Ответьте своими словами. Все поля обязательны — ответы увидит организатор.",
                      questions: { create: questions },
                    },
                  ],
                },
              },
            ],
          },
        },
      ],
    },
  },
});

console.log("Курс обновлён:", course.title);
console.log("Вопросов:", questions.length, "| открыт всем:", !course.restricted);
await db.$disconnect();
